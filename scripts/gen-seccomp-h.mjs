#!/usr/bin/env node
// Renders src/seccomp.ts SECCOMP_RULES into native/seccomp-table.h.
// The table is emitted as C initializers consumed by seatbelt-launcher.c.

import { SECCOMP_RULES } from "../dist/src/seccomp.js";

const ACT = { ALLOW: "SECCOMP_RET_ALLOW", EPERM: "(SECCOMP_RET_ERRNO|EPERM)", ENOSYS: "(SECCOMP_RET_ERRNO|ENOSYS)", KILL_PROCESS: "SECCOMP_RET_KILL_PROCESS" };

const rows = SECCOMP_RULES.map((r) => `  { "${r.syscall}", ${ACT[r.action]} },`).join("\n");
process.stdout.write(`/* generated by scripts/gen-seccomp-h.mjs — do not edit */
#ifndef SEATBELT_SECCOMP_TABLE_H
#define SEATBELT_SECCOMP_TABLE_H
struct sb_seccomp_rule { const char *name; unsigned int action; };
static const struct sb_seccomp_rule SB_SECCOMP_TABLE[] = {
${rows}
};
static const unsigned int SB_SECCOMP_TABLE_LEN = ${SECCOMP_RULES.length};
#endif
`);
